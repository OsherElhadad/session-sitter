'use strict';
const fs = require('fs');
const path = require('path');

const pkg = JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'package.json'), 'utf8'));
const now = new Date().toISOString();

const content =
  `// Auto-generated by scripts/gen-build-info.js — do not edit manually\n` +
  `export const BUILD_TIME = '${now}';\n` +
  `export const BUILD_VERSION = '${pkg.version}';\n`;

const outPath = path.join(__dirname, '..', 'src', 'buildInfo.ts');
fs.writeFileSync(outPath, content, 'utf8');
process.stdout.write('buildInfo: v' + pkg.version + ' @ ' + now + '\n');
