#!/usr/bin/env node
/**
 * Regenerate `../reference/settings-schema.json` from this repo's `package.json`.
 *
 * The snapshot is the doctor's last-resort source: someone reading these docs with no checkout and
 * no installed extension still gets real setting ids rather than an agent's recollection of them.
 * It is committed, so it needs a generator — hand-editing it would let it drift from the manifest
 * silently, which is the exact failure the snapshot exists to prevent.
 *
 * `ci/check-onboarding.sh` regenerates and diffs, so a settings change that skips this script
 * fails CI rather than shipping a stale snapshot.
 *
 * Usage:  node snapshot-schema.mjs [--check]
 *         --check  exit 1 if the committed file differs, and write nothing
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = join(HERE, '..', '..', '..');
const OUT = join(HERE, '..', 'reference', 'settings-schema.json');

const pkg = JSON.parse(readFileSync(join(REPO, 'package.json'), 'utf8'));
if (pkg.name !== 'session-sitter') {
  process.stderr.write(`snapshot-schema: ${join(REPO, 'package.json')} is not session-sitter\n`);
  process.exit(2);
}

const sections = [].concat(pkg.contributes.configuration);
const settings = {};
for (const section of sections) {
  for (const [id, decl] of Object.entries(section.properties ?? {})) {
    settings[id] = {
      section: section.title ?? null,
      type: decl.type,
      default: decl.default,
      enum: decl.enum ?? null,
      minimum: decl.minimum ?? null,
      maximum: decl.maximum ?? null,
      scope: decl.scope ?? 'window',
    };
  }
}

// The version is deliberately NOT included. It changes on every release while the settings do not,
// and a field that churns turns `--check` into noise — the snapshot would need regenerating for
// version bumps that changed nothing about the schema. `ss-config.mjs` reports the source as
// "committed snapshot" with a null version, which is the honest answer.
const payload = {
  comment: 'Generated by docs/onboarding/scripts/snapshot-schema.mjs — do not edit by hand. '
    + 'The offline fallback for ss-config.mjs when no checkout and no installed extension is found.',
  version: null,
  settings,
};
const text = JSON.stringify(payload, null, 2) + '\n';

if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync(OUT, 'utf8'); } catch { /* missing counts as different */ }
  if (current !== text) {
    process.stderr.write(
      '::error::docs/onboarding/reference/settings-schema.json is stale — '
      + 'run: node docs/onboarding/scripts/snapshot-schema.mjs\n');
    process.exit(1);
  }
  process.stdout.write(`settings-schema.json is current (${Object.keys(settings).length} settings)\n`);
  process.exit(0);
}

writeFileSync(OUT, text);
process.stdout.write(`wrote ${OUT} (${Object.keys(settings).length} settings)\n`);
